/** Writes BuildConfig.kt: the app version and build-time keys. Never committed. */
abstract class GenerateBuildConfig : DefaultTask() {
    @get:Input
    abstract val values: MapProperty<String, String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        fun literal(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val fields = values.get().toSortedMap().entries.joinToString("\n") { (k, v) ->
            "    const val $k: String = ${literal(v)}"
        }
        val dir = outputDir.get().asFile.resolve("de/fgchamburg/vodhelper/core")
        dir.mkdirs()
        dir.resolve("BuildConfig.kt").writeText(
            """
            |// Generated by :core:generateBuildConfig. Do not edit.
            |package de.fgchamburg.vodhelper.core
            |
            |object BuildConfig {
            |$fields
            |}
            |""".trimMargin(),
        )
    }
}

// Keys come from a Gradle property or an environment variable (the Makefile exports .env).
// Missing keys become "", so the build works without them.
fun key(name: String): Provider<String> =
    providers.gradleProperty(name).orElse(providers.environmentVariable(name)).orElse("")

val generateBuildConfig by tasks.registering(GenerateBuildConfig::class) {
    values.put("VERSION", project.version.toString())
    listOf("TWITCH_CLIENT_ID", "GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET").forEach { values.put(it, key(it)) }
    outputDir.set(layout.buildDirectory.dir("generated/buildconfig"))
}

kotlin.sourceSets.commonMain {
    kotlin.srcDir(generateBuildConfig.map { it.outputDir })
}

tasks.named<Test>("jvmTest") {
    systemProperty("app.version", project.version.toString())
}
